/**
 * Suite 09 — Action Discovery
 *
 * Visits every route and dynamically scans the rendered DOM for all
 * interactive controls: buttons, links, icons, FABs, dropdowns, tabs.
 *
 * Output:
 *   tests/reports/button-inventory.json   — full action inventory
 *   tests/reports/action-discovery-summary.md — human-readable summary
 *
 * Run:
 *   npx playwright test --project=action-discovery
 */

import { test } from '../fixtures/base';
import type { Page } from '@playwright/test';
import { ALL_ROUTES }   from '../helpers/routes';
import {
  DISCOVERY_SCRIPT,
  classifyAction,
  buildSelector,
  type RawElement,
  type DiscoveredAction,
} from '../helpers/action-discovery';
import { waitForPageLoad } from '../helpers/page-helpers';
import fs   from 'fs';
import path from 'path';

const BASE     = 'http://localhost:5173';
const OUT_DIR  = 'tests/reports';
const INV_FILE = path.join(OUT_DIR, 'button-inventory.json');

// ─── Types ────────────────────────────────────────────────────────────────────

interface InventoryEntry extends DiscoveredAction {
  discoveredAt: string;
}

interface Inventory {
  generated:    string;
  totalRoutes:  number;
  totalActions: number;
  byCategory:   Record<string, number>;
  byModule:     Record<string, number>;
  actions:      InventoryEntry[];
}

// ─── Discovery helpers ────────────────────────────────────────────────────────

async function discoverActionsOnPage(
  page: Parameters<typeof test>[1] extends (args: { page: infer P }) => unknown ? P : never,
  route: { path: string; module: string; name: string }
): Promise<InventoryEntry[]> {
  await page.goto(`${BASE}${route.path}`, { timeout: 25_000 }).catch(() => null);
  await waitForPageLoad(page).catch(() => null);

  // Allow async content to settle
  await page.waitForTimeout(500);

  let rawElements: RawElement[] = [];
  try {
    rawElements = await page.evaluate(DISCOVERY_SCRIPT) as RawElement[];
  } catch {
    return [];
  }

  const actions: InventoryEntry[] = [];

  for (const el of rawElements) {
    const { actionType, safetyCategory } = classifyAction(el);
    const { strategy, selector, text }   = buildSelector(el);

    actions.push({
      route:            route.path,
      module:           route.module,
      actionType,
      actionLabel:      el.label || el.text || '(unlabeled)',
      safetyCategory,
      selectorStrategy: strategy,
      selector,
      selectorText:     text,
      elementTag:       el.tag,
      elementClass:     el.className,
      discoveredAt:     new Date().toISOString(),
    });
  }

  return actions;
}

function buildSummary(inventory: Inventory): string {
  const now = new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' });

  const categoryRows = Object.entries(inventory.byCategory)
    .sort(([, a], [, b]) => b - a)
    .map(([cat, cnt]) => `| ${cat} | ${cnt} |`)
    .join('\n');

  const moduleRows = Object.entries(inventory.byModule)
    .sort(([, a], [, b]) => b - a)
    .map(([mod, cnt]) => `| ${mod} | ${cnt} |`)
    .join('\n');

  const safeCount      = inventory.actions.filter(a => a.safetyCategory === 'SAFE').length;
  const formCount      = inventory.actions.filter(a => a.safetyCategory === 'FORM').length;
  const approvalCount  = inventory.actions.filter(a => a.safetyCategory === 'APPROVAL').length;
  const dangerCount    = inventory.actions.filter(a => a.safetyCategory === 'DANGEROUS').length;
  const unknownCount   = inventory.actions.filter(a => a.safetyCategory === 'UNKNOWN').length;

  return `# Pulse ERP — Action Discovery Report
Generated: ${now} IST

## Summary

| Metric | Value |
|--------|-------|
| Routes scanned | ${inventory.totalRoutes} |
| Total actions discovered | ${inventory.totalActions} |
| SAFE (view/filter/export) | ${safeCount} |
| FORM (create/edit/save) | ${formCount} |
| APPROVAL (approve/reject) | ${approvalCount} |
| DANGEROUS (delete/purge) | ${dangerCount} |
| UNKNOWN | ${unknownCount} |

## By Safety Category

| Category | Count |
|----------|-------|
${categoryRows}

## By Module

| Module | Actions |
|--------|---------|
${moduleRows}

## Top Create Buttons (FORM actions)
${inventory.actions
  .filter(a => a.actionType === 'create-button')
  .slice(0, 20)
  .map(a => `- \`${a.route}\` → **${a.actionLabel}**`)
  .join('\n') || '— none found'}

## Top Dangerous Actions
${inventory.actions
  .filter(a => a.safetyCategory === 'DANGEROUS')
  .slice(0, 30)
  .map(a => `- \`${a.route}\` → **${a.actionLabel}** (${a.actionType})`)
  .join('\n') || '— none found'}

---
*Output: ${INV_FILE}*
*Generated by Pulse ERP Test Suite — Suite 09 Action Discovery*
`;
}

