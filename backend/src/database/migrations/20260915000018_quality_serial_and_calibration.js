/**
 * 20260915000018_quality_serial_and_calibration.js
 *
 * Inventory / traceability audit — finding 16 (quality traceability).
 *
 * ── WHAT WAS ACTUALLY WRONG (less than the audit first credited) ────────────
 *
 * The audit recorded "no per-serial QC, no test spec, no readings, no limits,
 * no calibration reference". Re-checked against the schema, most of that was
 * wrong: `test_runs` is rich and already carries test_stage, test_type,
 * test_spec_revision, station_name, executed_by, approved_by, bom_revision and
 * project_id, and `test_run_measurements` carries parameter, unit,
 * measured_value, min_limit, max_limit, target_value and result. Genealogy's
 * qc-history already reads both.
 *
 * Three things were genuinely missing, and one of them is worse than absence:
 *
 * 1. ⚠ `test_runs.serial_number` IS NOT A PANEL SERIAL. It holds values like
 *    `TR-13321` — the run's own number, generated by the seeding script from its
 *    own sequence. It matches `serial_numbers` on **0 of 5 rows**. This is the
 *    same defect already found in `fat_trackers.serial_number` (= fat_number+1).
 *    So the per-serial QC column existed, genealogy read it, and it linked to
 *    nothing — a join that silently returns empty rather than an error. It was
 *    also free text with no foreign key, so nothing could have caught it.
 *
 *    Fixed with a real `serial_id` FK. NOT backfilled: the existing values are
 *    generator output that matches no panel, and mapping them to real serials
 *    would invent a QC history.
 *
 * 2. NO INSTRUMENT OR CALIBRATION REFERENCE on a measurement. A reading without
 *    the instrument that took it, and that instrument's calibration state at the
 *    time, is not traceable evidence — it is a number. `calibration_equipment`
 *    already exists with certificate_number and next_calibration_date; nothing
 *    pointed at it.
 *
 *    The certificate and due date are COPIED onto the measurement, not only
 *    referenced. An instrument's current calibration record changes; what
 *    matters for a panel tested last March is the certificate that was in force
 *    THEN. A live join would silently rewrite the evidence at every recalibration.
 *
 * 3. NO COMPONENT-LEVEL QC LINK. `quality_inspections` had grn_id and
 *    production_order_id but no batch or serial, so an incoming inspection could
 *    not say which lot it passed.
 *
 * ── THE IQC INVERSION IS DATA, AND IS NOT SILENTLY "CORRECTED" ──────────────
 * 5 GRNs are stamped quality_status='passed' with ZERO inspection rows, while
 * the 4 GRNs that DO have inspections sit at 'pending'. Both directions are
 * wrong and they are wrong in opposite ways.
 *
 * This migration does not flip them to what they "should" say. Deriving a pass
 * from no inspection would manufacture a QC record; deriving it from the
 * inspections that exist would silently release material nobody released. What
 * it does instead is make the contradiction VISIBLE and impossible to repeat:
 *
 *   - `quality_status_source` records whether a status was derived from
 *     inspections or set directly, so the two can never again be confused.
 *   - Existing rows are marked 'unverified' where the stamp has no inspection
 *     behind it — which is what they are.
 *   - A view, v_iqc_status_conflicts, lists every GRN whose stamp disagrees with
 *     its inspections, so the 5 + 4 are a worklist rather than a footnote.
 *
 * Clearing that worklist is a quality decision for the people who own the
 * material, not a migration's to make.
 */

export async function up(knex) {
  const addFk = async (name, table, column, refTable, onDelete = 'SET NULL') => {
    const { rows } = await knex.raw(`SELECT 1 FROM pg_constraint WHERE conname = $1`, [name]);
    if (rows.length) return;
    await knex.raw(`
      ALTER TABLE ${table}
        ADD CONSTRAINT ${name} FOREIGN KEY (${column}) REFERENCES ${refTable}(id) ON DELETE ${onDelete}
    `);
  };

  // ── 1. A test run names a real panel ─────────────────────────────────────
  await knex.raw(`
    ALTER TABLE test_runs
      ADD COLUMN IF NOT EXISTS serial_id integer
  `);
  await addFk('test_runs_serial_fkey', 'test_runs', 'serial_id', 'serial_numbers');
  await knex.raw(`
    CREATE INDEX IF NOT EXISTS idx_test_runs_serial ON test_runs (serial_id) WHERE serial_id IS NOT NULL
  `);

  // A one-off, PROVABLE link: where a run's free-text serial_number does match a
  // real panel serial, record it. Live that is zero rows today — the seeded runs
  // carry their own run numbers — but it costs nothing and means any run that
  // was entered correctly by hand is not thrown away.
  await knex.raw(`
    UPDATE test_runs tr
       SET serial_id = sn.id
      FROM serial_numbers sn
     WHERE sn.serial_number = tr.serial_number
       AND sn.deleted_at IS NULL
       AND tr.serial_id IS NULL
       AND (sn.company_id IS NOT DISTINCT FROM tr.company_id OR tr.company_id IS NULL)
  `);

  // ── 2. A reading names the instrument and its calibration AT THE TIME ────
  await knex.raw(`
    ALTER TABLE test_run_measurements
      ADD COLUMN IF NOT EXISTS instrument_id                integer,
      ADD COLUMN IF NOT EXISTS instrument_serial            text,
      ADD COLUMN IF NOT EXISTS calibration_certificate_no   text,
      ADD COLUMN IF NOT EXISTS calibration_due_date         date,
      ADD COLUMN IF NOT EXISTS calibration_valid_at_test    boolean
  `);
  await addFk('trm_instrument_fkey', 'test_run_measurements', 'instrument_id', 'calibration_equipment');
  await knex.raw(`
    CREATE INDEX IF NOT EXISTS idx_trm_instrument
      ON test_run_measurements (instrument_id) WHERE instrument_id IS NOT NULL
  `);

  // ── 3. An inspection names the lot and unit it inspected ─────────────────
  await knex.raw(`
    ALTER TABLE quality_inspections
      ADD COLUMN IF NOT EXISTS batch_id            integer,
      ADD COLUMN IF NOT EXISTS serial_id           integer,
      ADD COLUMN IF NOT EXISTS component_serial_id integer,
      ADD COLUMN IF NOT EXISTS instrument_id       integer
  `);
  await addFk('qi_batch_fkey',      'quality_inspections', 'batch_id',            'inventory_batches');
  await addFk('qi_serial_fkey',     'quality_inspections', 'serial_id',           'serial_numbers');
  await addFk('qi_cserial_fkey',    'quality_inspections', 'component_serial_id', 'serial_numbers');
  await addFk('qi_instrument_fkey', 'quality_inspections', 'instrument_id',       'calibration_equipment');
  await knex.raw(`
    CREATE INDEX IF NOT EXISTS idx_qi_batch  ON quality_inspections (batch_id)  WHERE batch_id IS NOT NULL;
    CREATE INDEX IF NOT EXISTS idx_qi_serial ON quality_inspections (serial_id) WHERE serial_id IS NOT NULL;
  `);

  // ── 4. Make the IQC contradiction visible, not quietly resolved ──────────
  await knex.raw(`
    ALTER TABLE goods_receipt_notes
      ADD COLUMN IF NOT EXISTS quality_status_source text,
      ADD COLUMN IF NOT EXISTS quality_status_at     timestamptz,
      ADD COLUMN IF NOT EXISTS quality_status_by     integer
  `);
  const { rows: chk } = await knex.raw(
    `SELECT 1 FROM pg_constraint WHERE conname = 'grn_quality_status_source_chk'`);
  if (!chk.length) {
    await knex.raw(`
      ALTER TABLE goods_receipt_notes
        ADD CONSTRAINT grn_quality_status_source_chk
        CHECK (quality_status_source IS NULL
               OR quality_status_source = ANY (ARRAY['derived','manual','unverified','not_required']))
    `);
  }

  // Name what the existing rows actually are. A 'passed' with no inspection
  // behind it is UNVERIFIED — that is a statement of fact about the record, not
  // a judgement about the material, and it is the honest label for it.
  await knex.raw(`
    UPDATE goods_receipt_notes g
       SET quality_status_source = CASE
             WHEN g.quality_status IS NULL OR g.quality_status = 'not_required' THEN 'not_required'
             WHEN EXISTS (SELECT 1 FROM quality_inspections qi WHERE qi.grn_id = g.id) THEN 'derived'
             ELSE 'unverified'
           END
     WHERE g.quality_status_source IS NULL
  `);

  // The worklist. Both directions of the contradiction, each labelled.
  await knex.raw(`
    CREATE OR REPLACE VIEW v_iqc_status_conflicts AS
    SELECT g.id                AS grn_id,
           g.grn_number,
           g.company_id,
           g.received_date,
           g.quality_status,
           g.quality_status_source,
           COUNT(qi.id)        AS inspection_count,
           COUNT(qi.id) FILTER (WHERE LOWER(COALESCE(qi.overall_result,'')) IN ('pass','passed','accepted')) AS passed_count,
           COUNT(qi.id) FILTER (WHERE LOWER(COALESCE(qi.overall_result,'')) IN ('fail','failed','rejected')) AS failed_count,
           CASE
             WHEN g.quality_status = 'passed' AND COUNT(qi.id) = 0
               THEN 'released_without_inspection'
             WHEN g.quality_status = 'pending' AND COUNT(qi.id) > 0
               THEN 'inspected_but_not_released'
             WHEN g.quality_status = 'passed'
                  AND COUNT(qi.id) FILTER (WHERE LOWER(COALESCE(qi.overall_result,'')) IN ('fail','failed','rejected')) > 0
               THEN 'released_despite_failure'
           END AS conflict
      FROM goods_receipt_notes g
      LEFT JOIN quality_inspections qi ON qi.grn_id = g.id
     WHERE g.deleted_at IS NULL
     GROUP BY g.id, g.grn_number, g.company_id, g.received_date,
              g.quality_status, g.quality_status_source
    HAVING (g.quality_status = 'passed' AND COUNT(qi.id) = 0)
        OR (g.quality_status = 'pending' AND COUNT(qi.id) > 0)
        OR (g.quality_status = 'passed'
            AND COUNT(qi.id) FILTER (WHERE LOWER(COALESCE(qi.overall_result,'')) IN ('fail','failed','rejected')) > 0)
  `);
}

